    /// <remarks>
    /// <para>
    /// To use custom suffixes or names, subclass <see cref="BigNumberNames"/>, override
    /// <see cref="ShortNames"/> and/or <see cref="LongNames"/>, and assign your subclass
    /// to <see cref="Current"/> before formatting any values:
    /// </para>
    /// <code>
    /// public class MyNames : BigNumberNames
    /// {
    ///     public override string[] ShortNames => new[] { "k", "m", "b", "t" };
    /// }
    ///
    /// BigNumberNames.Current = new MyNames();
    /// </code>
    /// <para>
    /// Both arrays are indexed starting at the thousands group (10³). Index 0 = Thousand/K,
    /// index 1 = Million/M, and so on. Values below 1,000 are shown without a suffix.
    /// If a value's group index exceeds the array length, scientific notation is used as
    /// a fallback.
